import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
await fs.mkdir('artifacts',{recursive:true});
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1100}});
process.on('uncaughtException',async e=>{console.error(e);await browser.close();process.exit(1)});
const errors=[];page.on('pageerror',e=>errors.push(e.message));

await page.goto('http://127.0.0.1:5173');
await page.locator('canvas').waitFor();
await page.locator('#start').click();
await page.waitForTimeout(200);
await page.locator('#accept').click();
await page.locator('[data-cook="chicken"]').click();
await page.locator('[data-cook="drink"]').click();
await page.waitForFunction(()=>document.getElementById('status-chicken').textContent.includes('พร้อม 1 ชิ้น'));
await page.locator('[data-add="chicken"]').click();
await page.locator('[data-add="drink"]').click();
await page.locator('#serve').click();
assert.match(await page.locator('#served').innerText(),/^1 /);
assert.equal(await page.locator('#profit').innerText(),'฿66');
await page.screenshot({path:'artifacts/desktop.png',fullPage:true});
console.log('PASS: mouse order and profit');
await page.locator('#pause').click();
const time=await page.locator('#time').innerText();
await page.waitForTimeout(5000);
assert.equal(await page.locator('#time').innerText(),time);
await page.locator('#resume').click();
console.log('PASS: pause');
await page.waitForTimeout(10000);
await page.locator('canvas').click({position:{x:20,y:20}});
await page.keyboard.press('e');
assert.match(await page.locator('#orders').innerText(),/กำลังเตรียม/);
await page.keyboard.press('2');
await page.waitForFunction(()=>document.getElementById('status-fries').textContent.includes('พร้อม 1 ชิ้น'));
await page.keyboard.press('w');
assert.equal(await page.locator('.tray-food').count(),1);
await page.keyboard.press('Backspace');
assert.equal(await page.locator('.tray-food').count(),0);
console.log('PASS: keyboard');
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'artifacts/mobile.png',fullPage:true});
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
console.log('PASS: mobile; waiting for full shift end');
await page.waitForFunction(()=>document.getElementById('overlay').dataset.mode==='end',{},{timeout:210000});
assert.equal(await page.locator('#overlay').getAttribute('data-mode'),'end');
await page.locator('#restart').click();
assert.match(await page.locator('#served').innerText(),/^0 /);
assert.equal(await page.locator('#revenue').innerText(),'฿0');
assert.equal(errors.length,0,errors.join('\n'));
console.log('PASS: boot, mouse cooking/serve/profit, pause, keyboard, mobile width, shift end, restart; no browser errors.');
await browser.close();
